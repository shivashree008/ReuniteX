INSERT INTO camps (name)
SELECT DISTINCT COALESCE(NULLIF(registered_camp, ''), NULLIF(camp_name, ''))
FROM people
WHERE COALESCE(NULLIF(registered_camp, ''), NULLIF(camp_name, '')) IS NOT NULL
    AND COALESCE(NULLIF(registered_camp, ''), NULLIF(camp_name, '')) <> 'Not assigned'
ON CONFLICT (name) DO NOTHING;

UPDATE people AS person
SET camp_id = camp.id
FROM camps AS camp
WHERE person.camp_id IS NULL
    AND camp.name = COALESCE(NULLIF(person.registered_camp, ''), NULLIF(person.camp_name, ''));

INSERT INTO families (family_id, family_head, household_address)
SELECT family_id, MAX(family_head), MAX(COALESCE(NULLIF(full_address, ''), NULLIF(address, '')))
FROM people
WHERE NULLIF(family_id, '') IS NOT NULL
GROUP BY family_id
ON CONFLICT (family_id) DO UPDATE SET
        family_head = COALESCE(families.family_head, EXCLUDED.family_head),
        household_address = COALESCE(families.household_address, EXCLUDED.household_address);

UPDATE people AS person
SET family_uuid = family.id
FROM families AS family
WHERE person.family_uuid IS NULL AND family.family_id = person.family_id;

