CREATE TABLE IF NOT EXISTS reunification_cases (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    missing_person_id BIGINT NOT NULL UNIQUE REFERENCES people(id) ON DELETE RESTRICT,
    status TEXT NOT NULL DEFAULT 'OPEN'
        CHECK (status IN ('OPEN', 'POTENTIAL_MATCH', 'UNDER_VERIFICATION', 'VERIFIED', 'REUNIFICATION_PENDING', 'REUNITED', 'CLOSED')),
    revision INTEGER NOT NULL DEFAULT 1 CHECK (revision > 0),
    closed_at TIMESTAMPTZ,
    closed_by UUID REFERENCES staff_users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((status = 'CLOSED') = (closed_at IS NOT NULL))
);

INSERT INTO reunification_cases (missing_person_id)
SELECT id FROM people WHERE status = 'missing'
ON CONFLICT (missing_person_id) DO NOTHING;

