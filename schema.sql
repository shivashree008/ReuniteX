CREATE TABLE IF NOT EXISTS candidate_matches (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    source_person_id BIGINT NOT NULL REFERENCES people(id) ON DELETE RESTRICT,
    candidate_person_id BIGINT NOT NULL REFERENCES people(id) ON DELETE RESTRICT,
    clue_scores JSONB NOT NULL,
    combined_score NUMERIC(5, 2) NOT NULL CHECK (combined_score BETWEEN 0 AND 100),
    explanation JSONB,
    explanation_ready BOOLEAN NOT NULL DEFAULT FALSE,
    status TEXT NOT NULL DEFAULT 'candidate_found'
        CHECK (status IN ('candidate_found', 'verified', 'approved', 'rejected', 'follow_up')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (source_person_id, candidate_person_id),
    CHECK (source_person_id <> candidate_person_id)
);

CREATE TABLE IF NOT EXISTS verification_reviews (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    candidate_match_id UUID NOT NULL REFERENCES candidate_matches(id) ON DELETE RESTRICT,
    reviewer_id UUID REFERENCES staff_users(id) ON DELETE SET NULL,
    reviewer_username TEXT NOT NULL,
    action TEXT NOT NULL CHECK (action IN ('evidence_recorded', 'approved', 'rejected', 'follow_up')),
    evidence JSONB NOT NULL DEFAULT '{}'::jsonb,
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

